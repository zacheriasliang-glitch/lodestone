#!/usr/bin/env python3
"""Verify the exact runtime/GUI source inventory without importing application code."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify(root):
    root = Path(root).resolve()
    provenance = json.loads((root / "SOURCE_PROVENANCE.json").read_text())
    if provenance.get("schema") != "lodestone-desktop-source-provenance/v1":
        raise ValueError("Unrecognized source provenance")
    expected = provenance["exported_files"]
    actual = {}
    for folder in ("runtime", "gui"):
        base = root / folder
        if base.is_symlink() or not base.is_dir():
            raise ValueError("Source component must be a directory, not a symbolic link")
        for path in base.rglob("*"):
            if path.is_symlink():
                raise ValueError("Source payload contains a symbolic link")
            if path.is_file():
                if "__pycache__" in path.parts or path.suffix == ".pyc":
                    raise ValueError("Source payload contains generated bytecode")
                actual[path.relative_to(root).as_posix()] = digest(path)
    if set(actual) != set(expected):
        raise ValueError("Source payload file inventory differs")
    for name, identity in expected.items():
        if actual[name] != identity["sha256"]:
            raise ValueError("Source payload changed: " + name)
    catalogue = json.loads((root / "runtime/docs/loom-integration-map.json").read_text())
    if (len(catalogue["programme_rows"]) != 31 or
            len(catalogue["toolkit_families"]) != 15):
        raise ValueError("Programme or toolkit inventory differs")
    for name in ("runtime/LICENSE", "gui/LICENSE"):
        if not (root / name).is_file():
            raise ValueError("Component licence is missing")
    return {"schema": "lodestone-desktop-payload-check/v1", "status": "VERIFIED",
            "files": len(actual), "programme_rows": 31, "toolkit_families": 15,
            "scope": "File inventory, content hashes and catalogue counts; not installation or model validation"}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent)
    args = parser.parse_args()
    print(json.dumps(verify(args.root), indent=2, sort_keys=True))
