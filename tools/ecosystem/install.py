#!/usr/bin/env python3
"""Install only a small checkout launcher; never replace another executable."""
import argparse
import json
import os
from pathlib import Path
import shlex
import sys


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bin-dir", type=Path, default=Path.home() / ".local/bin")
    args = parser.parse_args(argv)
    try:
        if os.name == "nt":
            raise ValueError("The optional shell launcher is for macOS/Linux. On Windows use python PATH/TO/lodestone.py instead.")
        if sys.version_info < (3, 10):
            raise ValueError("Python 3.10 or later is required")
        script = Path(__file__).resolve().with_name("lodestone")
        target = args.bin_dir.expanduser().resolve() / "lodestone"
        raw = ("#!/bin/sh\n# Lodestone checkout launcher; generated by tools/ecosystem/install.py\n"
               + "exec " + shlex.quote(sys.executable) + " -B " + shlex.quote(str(script)) + ' "$@"\n').encode()
        if target.exists() or target.is_symlink():
            if target.is_symlink() or target.read_bytes() != raw:
                raise ValueError(f"Refusing to replace existing launcher: {target}")
            status = "UNCHANGED"
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            with target.open("xb") as handle:
                handle.write(raw)
            target.chmod(0o755)
            status = "INSTALLED"
        print(json.dumps({"status": status, "launcher": str(target), "checkout": str(script.parents[2]),
                          "python": sys.executable, "note": "No services, credentials or stores changed"}, indent=2))
        return 0
    except (OSError, ValueError) as exc:
        print(json.dumps({"error": str(exc)}), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
