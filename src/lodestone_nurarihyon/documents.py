"""Bounded document capture through the existing Pando/Bezoar contracts.

This structural interpretation preserves literal text. It does not infer its
truth, adopt instructions, register operators, or activate a candidate. The
controller independently validates staging; documents never select code.
"""
from pathlib import Path
import re

from .common import canonical, create_file, digest, read_bytes, strict_json
from .plans import PlanError, _current, _typed_equal

TOOLKIT = "bezoar.document/v1"
SOURCE_SCHEMA = "nurarihyon-document-source/v1"
MAX_SOURCE_BYTES = 65536
CHUNK_CHARACTERS = 4096  # Existing kernel quotation bound, measured in characters.


def parse_document_source(raw):
    try:
        value = strict_json(raw, MAX_SOURCE_BYTES)
        if (type(value) is not dict or set(value) != {"schema", "title", "text"}
                or value["schema"] != SOURCE_SCHEMA
                or type(value["title"]) is not str or not value["title"].strip()
                or len(value["title"]) > 300
                or type(value["text"]) is not str or not value["text"].strip()):
            raise ValueError("Document fields or text invalid")
        if len(value["title"].encode("utf-8")) > 300:
            raise ValueError("Document title exceeds Pando UTF-8 byte bound")
        value["text"].encode("utf-8")
        if len(split_document(value["text"])) > 32:
            raise ValueError("Document exceeds kernel operator count")
        return value
    except (ValueError, TypeError, RecursionError):
        raise PlanError("REJECTED_VALIDATION", "Invalid bounded UTF-8 document source") from None


def split_document(text):
    return [text[i:i + CHUNK_CHARACTERS] for i in range(0, len(text), CHUNK_CHARACTERS)]


def make_document_plan(raw, current_view):
    source = parse_document_source(raw)
    document = source["text"].encode("utf-8")
    return {"schema": "nurarihyon-document-plan/v1", "toolkit": TOOLKIT,
            "source_sha256": digest(raw), "document_sha256": digest(document),
            "document_bytes": len(document), "title": source["title"],
            "chunk_count": len(split_document(source["text"])),
            "interpretation": "literal-document-parts/v1", "baseline": _current(current_view),
            "authority": "PROPOSAL_ONLY", "candidate_activation": "NONE"}


def validate_document_plan(plan, raw, current_view):
    if type(plan) is not dict or plan.get("source_sha256") != digest(raw):
        raise PlanError("SOURCE_DRIFT", "Document envelope differs from planned source")
    expected = make_document_plan(raw, current_view)
    if not _typed_equal(plan, expected):
        raise PlanError("REJECTED_VALIDATION", "Document plan differs from independent recomputation")


def prepare_document(document, title, output):
    raw = read_bytes(Path(document), MAX_SOURCE_BYTES)
    try:
        text = raw.decode("utf-8")
    except UnicodeError:
        raise ValueError("Document is not UTF-8") from None
    envelope = canonical({"schema": SOURCE_SCHEMA, "title": title, "text": text})
    parse_document_source(envelope)  # JSON expansion also counts against admission.
    create_file(Path(output), envelope)
    return {"schema": "nurarihyon-document-capture/v1", "path": str(Path(output)),
            "source_sha256": digest(envelope), "document_sha256": digest(raw),
            "document_bytes": len(raw), "authority": "NONE", "task_created": False}


def question(task_id):
    return "Retain exact document parts as inert evidence for authorized task " + task_id + "."


def proposal_for(source, source_id, request_handle, task_id):
    # The kernel disallows empty/whitespace-only quotes. Such a part uses an
    # anchor from the same source; the controller still checks every literal
    # part, its position, and complete reconstruction independently.
    anchor = next(c for c in source["text"] if not c.isspace())
    return {"schema": "kernel-digestion/v1", "request_handle": request_handle,
            "id": "document-" + task_id, "actor": "host",
            "operators": {
                f"document_part_{i:03d}": {"value": part, "source": source_id + ".txt",
                    "quote": part if part.strip() else anchor,
                    "rationale": f"Literal document part {i}; exact position and reconstruction checked by the controller."}
                for i, part in enumerate(split_document(source["text"]))},
            "instructions": [], "rejected": [],
            "uncertainties": ["Structural interpretation generated by fixed Nurarihyon code under host task approval; not host-authored semantics.",
                              "Text is preserved, not adopted. Semantic truth and applicability remain unreviewed; activation NONE."]}


def build_document(board, raw, task):
    """Worker-only staged writes through real existing organs."""
    validate_document_plan(task["plan"], raw, board.settings())
    source = parse_document_source(raw)
    document = source["text"].encode("utf-8")
    source_id = board.ingest(document, title=source["title"], uri="sha256:" + digest(document),
                             author="host", kind="file")
    request = board.eat([source_id], author="host", question=question(task["id"]),
                        title="Authorized document ingestion")
    proposal = proposal_for(source, source_id, board.artifact(request)["handle"], task["id"])
    candidate = board.digest(request, proposal, author="host", title="Literal document interpretation")
    return {"toolkit": TOOLKIT, "source_id": source_id, "request_artifact": request,
            "candidate_artifact": candidate, "document_sha256": digest(document),
            "interpretation": "literal-document-parts/v1", "activation": "NONE",
            "board_verification": board.verify()}


def validate_document_stage(board, parent, raw, task, plan, report, policy):
    """Controller acceptance; no publication or execution of candidate text."""
    from .common import tree_inventory
    from lodestone_machinery.organs.ingest import read_ingest
    from lodestone_pando.store import encoded
    validate_document_plan(plan, raw, parent.settings())
    for key in ("source_id", "request_artifact", "candidate_artifact"):
        identity = report.get(key)
        if type(identity) is not str or re.fullmatch(r"[0-9a-f]{64}", identity) is None:
            raise ValueError("Document worker report has an invalid " + key)
    source = parse_document_source(raw)
    document = source["text"].encode("utf-8")
    if report.get("toolkit") != TOOLKIT or report.get("activation") != "NONE":
        raise ValueError("Document worker contract mismatch")
    if board.settings() != parent.settings():
        raise ValueError("Document task changed the board view")
    before, after = parent.state(), board.state()
    if before["posts"] != after["posts"]:
        raise ValueError("Document task changed posts")
    for collection in ("sources", "artifacts"):
        existing = {x["id"]: x for x in after[collection]}
        if any(existing.get(x["id"]) != x for x in before[collection]):
            raise ValueError("Document task changed existing history")
    with parent.connection() as a, board.connection() as b:
        for sql in ("SELECT * FROM metadata ORDER BY key",
                    "SELECT type,name,tbl_name,sql FROM sqlite_master ORDER BY name"):
            if [tuple(x) for x in a.execute(sql)] != [tuple(x) for x in b.execute(sql)]:
                raise ValueError("Document task changed metadata or database schema")
    source_id = digest(encoded(["sha256:" + digest(document), digest(document)]).encode("utf-8"))
    if report.get("source_id") != source_id or report.get("document_sha256") != digest(document):
        raise ValueError("Document source binding mismatch")
    captured = board.source(source_id)
    if (captured["text"].encode("utf-8") != document or captured["sha256"] != digest(document)
            or captured["bytes"] != len(document) or captured["uri"] != "sha256:" + digest(document)
            or captured["author"] != "host" or captured["kind"] != "file"):
        raise ValueError("Document capture mismatch")
    old_sources = {x["id"] for x in before["sources"]}
    if {x["id"] for x in after["sources"]} != old_sources | {source_id}:
        raise ValueError("Unexpected document source additions")
    if source_id not in old_sources and captured["title"] != source["title"]:
        raise ValueError("Document title mismatch")
    request, candidate = (board.artifact(report[k]) for k in ("request_artifact", "candidate_artifact"))
    if (request["stage"] != "EAT" or request["parent_id"] is not None
            or candidate["stage"] != "DIGEST" or candidate["parent_id"] != request["id"]
            or request["title"] != "Authorized document ingestion"
            or request["summary"] != question(task["id"])
            or candidate["title"] != "Literal document interpretation"
            or candidate["summary"] != "Source-cited candidate; semantic review remains required. No model or source instruction executed."
            or any(a["source_ids"] != [source_id] or a["author"] != "host" for a in (request, candidate))):
        raise ValueError("Document artifact lineage mismatch")
    for artifact, owner, kind in ((request, "eat", "digestion_request"), (candidate, "eat", "kernel_blueprint")):
        if (artifact["id"] != digest(encoded([artifact["stage"], artifact["handle"], "host", artifact["parent_id"]]).encode("utf-8"))
                or artifact["record"]["owner"] != owner or artifact["record"]["kind"] != kind):
            raise ValueError("Document artifact identity/producer mismatch")
    old_artifacts = {x["id"] for x in before["artifacts"]}
    new_ids = {request["id"], candidate["id"]}
    if (len(new_ids) != 2 or new_ids & old_artifacts
            or {x["id"] for x in after["artifacts"]} != old_artifacts | new_ids):
        raise ValueError("Document task must add exactly two task-bound artifacts")
    req = request["record"]["payload"]
    ingestion = req["ingest_handle"]
    ingested = read_ingest(board.plumber.records, ingestion, "nurarihyon")
    expected_sources = [{"id": source_id + ".txt", "path": source_id + ".txt",
                         "sha256": digest(document), "bytes": len(document), "text": source["text"]}]
    if (req.get("schema") != "kernel-eat-request/v1" or req.get("question") != question(task["id"])
            or req.get("sources") != expected_sources or ingested["sources"] != expected_sources
            or request["record"]["links"] != [ingestion]):
        raise ValueError("Document ingestion/request source mismatch")
    proposal = proposal_for(source, source_id, request["handle"], task["id"])
    profile = {"schema": "kernel-profile/v1", "id": proposal["id"], "kind": "inferred-candidate",
               "source_refs": [{"source": source_id + ".txt", "sha256": digest(document), "ingest_handle": ingestion}],
               "operators": {k: v["value"] for k, v in proposal["operators"].items()}, "instructions": [],
               "lineage": {"operation": "EAT", "request": request["handle"], "actor": "host",
                           "proposal_sha256": digest(canonical(proposal))}}
    expected = {"schema": "kernel-blueprint/v1", "profile": profile, "digestion": proposal,
                "status": "CANDIDATE", "semantic_verdict": "UNREVIEWED", "source_instructions_executed": False,
                "identity_transfer": False, "activation": "NONE", "ingest_handle": ingestion}
    if (not _typed_equal(candidate["record"]["payload"], expected)
            or candidate["record"]["links"] != sorted([request["handle"], ingestion])):
        raise ValueError("Document interpretation differs from independent source reconstruction")
    previous = {x["path"]: x for x in tree_inventory(parent.home, max_bytes=policy["max_stage_bytes"])}
    current = {x["path"]: x for x in tree_inventory(board.home, max_bytes=policy["max_stage_bytes"])}
    for name, item in previous.items():
        if name != "pando.sqlite3" and current.get(name) != item:
            raise ValueError("Document task changed an immutable file")
    allowed = {"captures/" + source_id + ".txt"}
    for handle in (ingestion, request["handle"], candidate["handle"]):
        owner, identity = handle.split(":")
        allowed.add(f"kernel/organs/{owner}/records/{identity}.json")
    if set(current) - set(previous) - allowed:
        raise ValueError("Document task added undeclared files")
    return report
